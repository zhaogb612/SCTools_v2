_SVG_TPL = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
            'stroke="__COLOR__" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{}</svg>')

_cache = {}
_ensured = False


def ensure_icon_files():
    """把内置 SVG 释放为 resources/icons/*.svg（资源文件夹规范）"""
    global _ensured
    if _ensured:
        return
    os.makedirs(config.ICON_DIR, exist_ok=True)
    for name, body in SVG_ICONS.items():
        path = os.path.join(config.ICON_DIR, name + ".svg")
        with open(path, "w", encoding="utf-8") as f:
            f.write(_SVG_TPL.format(body))
    _ensured = True


def _solid(color):
    """Qt SVG 不支持 rgba() 颜色，统一转成 hex（图标不需要透明度）"""
    if color.startswith("rgba("):
        parts = color[5:-1].split(",")
        return "#{:02X}{:02X}{:02X}".format(int(parts[0]), int(parts[1]), int(parts[2]))
    return color


def icon(name, color="#6b7686"):
    """按名称与颜色获取 QIcon"""
    key = (name, color)
    if key in _cache:
        return _cache[key]
    ensure_icon_files()
    color = _solid(color)
    path = os.path.join(config.ICON_DIR, name + ".svg")
    try:
        with open(path, "r", encoding="utf-8") as f:
            svg = f.read()
    except OSError:
        svg = None
    if svg is None and name in SVG_ICONS:
        svg = _SVG_TPL.format(SVG_ICONS[name])  # 文件缺失/损坏时用内存模板兜底
    img = QImage.fromData(svg.replace("__COLOR__", color).encode("utf-8"))
    if img.isNull() and name in SVG_ICONS:
        img = QImage.fromData(_SVG_TPL.format(SVG_ICONS[name])
                              .replace("__COLOR__", color).encode("utf-8"))
    ic = QIcon(QPixmap.fromImage(img))
    _cache[key] = ic
    return ic
